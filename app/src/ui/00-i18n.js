function tr(s) {
  if (s == null || lang() !== 'en') return s;
  const raw = String(s);
  const key = raw.trim();
  if (!key) return raw;
  if (Object.prototype.hasOwnProperty.call(EN, key)) {
    const i = raw.indexOf(key);
    return raw.slice(0, i) + EN[key] + raw.slice(i + key.length);
  }
  for (let i = 0; i < EN_RE.length; i++) {
    const re = EN_RE[i][0];
    if (re.test(key)) {
      const next = key.replace(re, EN_RE[i][1]); // string o función
      const at = raw.indexOf(key);
      return raw.slice(0, at) + next + raw.slice(at + key.length);
    }
  }
  return raw;
}

function translateDom(root) {
  if (!root || lang() !== 'en') return;
  const textSkip = root.querySelectorAll('script, style, textarea, .f-t, .f-d, .f-r, .f-ref');
  const blocked = new Set();
  textSkip.forEach((el) => { blocked.add(el); el.querySelectorAll('*').forEach((n) => blocked.add(n)); });
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const n of nodes) {
    if (n.parentElement && blocked.has(n.parentElement)) continue;
    const next = tr(n.nodeValue);
    if (next !== n.nodeValue) n.nodeValue = next;
  }
  root.querySelectorAll('[placeholder], [aria-label], [title]').forEach((el) => {
    if (el.closest('script, style, .f-t, .f-d, .f-r, .f-ref')) return;
    for (const attr of ['placeholder', 'aria-label', 'title']) {
      if (!el.hasAttribute(attr)) continue;
      const next = tr(el.getAttribute(attr));
      if (next !== el.getAttribute(attr)) el.setAttribute(attr, next);
    }
  });
}

function localize() {
  if (lang() !== 'en') return;
  for (const id of ['side', 'top', 'view', 'palette', 'toast']) {
    const el = document.getElementById(id);
    if (el) translateDom(el);
  }
}
